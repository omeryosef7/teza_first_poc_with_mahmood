#!/usr/bin/env python3
"""Emit p2b_runner argv lines for P3 (truncation/removal) and P4 (head-restricted) arms. score_behavior flags are
taken from p2b_emit.common/KO (byte-identical to the P2b recipe). Every arm is `op:<file>:<KEY>` (stored operator)
or `rand:<file>:<KEY>:<seed>` (rank- and per-module-norm-matched random operator regenerated by the runner)."""
import argparse, os, sys
import torch
REPO = "/home/sharifm/students/omeryosef/first_poc/teza_first_poc_with_mahmood"
sys.path.insert(0, os.path.join(REPO, "research", "heretic_csi"))
from p2b_emit import common, KO   # noqa: E402

SB = "python src/boombness/score_behavior.py"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--what", required=True, choices=("p3", "p4"))
    ap.add_argument("--cw", required=True); ap.add_argument("--snap", required=True); ap.add_argument("--excl", required=True)
    ap.add_argument("--prefix", required=True); ap.add_argument("--file", required=True)
    ap.add_argument("--nrand", type=int, default=40, help="P3: random norm-matched controls per TOP-k key")
    ap.add_argument("--n-rh8", type=int, default=60, help="P4: random-8-head fitted controls")
    ap.add_argument("--base-arm", action="store_true", help="also apply the primary key on BASE (preservation)")
    a = ap.parse_args()
    C = common(a.cw, a.snap, a.excl, 0)
    ops = torch.load(a.file, map_location="cpu")["operators"]
    out = []
    em = lambda spec, flags, arm: out.append(f"{spec}\t{SB} {flags} --arm {arm} --tag {a.prefix}_{arm}")  # noqa: E731
    if a.what == "p3":
        for key in sorted(ops):
            em(f"op:{a.file}:{key}", f"{C} {KO}", f"KO_{key}")
        for key in sorted(k for k in ops if k.startswith("TOP") and not k.endswith("N")):
            for i in range(a.nrand):
                em(f"rand:{a.file}:{key}:{9000 + 100 * int(key[3:]) + i}", f"{C} {KO}", f"KO_RAND_{key}_{i}")
    else:
        for key in ("TOP8", "FULLO", "MLP", "ATTNMLP", "H2", "CELL_L10H2"):
            em(f"op:{a.file}:{key}", f"{C} {KO}", f"KO_{key}")
        if a.base_arm:
            em(f"op:{a.file}:TOP8", C, "BASE_TOP8")
        for j in range(a.n_rh8):
            em(f"op:{a.file}:RH8_{j}", f"{C} {KO}", f"KO_RH8_{j}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
